-- Toolpath recalculation check, ported 2026-08-23 from
-- ClockReviewReport.lua (see that file's
-- RECALCULATE_TOOLPATHS_TO_CHECK_ERRORS comment for the full original
-- discussion). DESTRUCTIVE - marks the job "modified" in VCarve even
-- when nothing was actually wrong. This is the only known way to
-- detect a toolpath whose source vectors have been deleted: no
-- documented read-only "IsBroken"/"SourceVectorsMissing" flag exists
-- on the Toolpath object (checked the full documented property list;
-- the closest candidate, ToolpathStats.IsValid, only reflects whether
-- the toolpath has EVER been calculated, not whether its current
-- source geometry still exists). VCarve's own UI gives no visible
-- indication of this either - Clock's original motivating case was a
-- real leftover toolpath ("Micrometer" in a test file) referencing
-- deleted vectors, with nothing in the Toolpaths list or elsewhere
-- flagging it.
--
-- See the STANDING NOTE at the top of this file - do not save the
-- student's file after running this gadget unless you mean to keep
-- the change.
--
-- NOT YET LIVE-VALIDATED against a real Box Project file with a
-- genuine deleted-vector toolpath - ported directly from Clock's
-- proven mechanism, but Box's own geometry/toolpath shapes haven't
-- been used to confirm this specific failure mode fires cleanly here
-- too.
RECALCULATE_TOOLPATHS_TO_CHECK_ERRORS = true

function FormatToolpathRecalculationReport(job)
    local r = NewReport()
    r:Blank()
    r:Header("TOOLPATH RECALCULATION CHECK")

    if not RECALCULATE_TOOLPATHS_TO_CHECK_ERRORS then
        r:Line("  (disabled - set RECALCULATE_TOOLPATHS_TO_CHECK_ERRORS = true to re-enable)")
        return r
    end

    r:Line("  REMINDER: this Gadget marks the file 'modified' in VCarve \226\128\148 don't save over the student's original", "warning")

    local tpm = ToolpathManager()

    -- First pass: collect every toolpath's name + id WITHOUT
    -- recalculating anything yet - recalculating while iterating the
    -- manager's own list risks corrupting the iteration (the SDK
    -- warns the old toolpath is destroyed and replaced internally).
    local targets = {}
    local pos = tpm:GetHeadPosition()
    while pos ~= nil do
        local tp
        tp, pos = tpm:GetNext(pos)
        local ok_id, id_wrapper = pcall(function()
            local w = luaUUID()
            w:SetId(tp.Id)
            return w
        end)
        if ok_id then
            table.insert(targets, { name = tp.Name, id_wrapper = id_wrapper })
        else
            table.insert(targets, { name = tp.Name, id_wrapper = nil })
        end
    end

    -- Second pass: recalculate each one individually, re-finding its
    -- position each time - never reusing a toolpath variable across a
    -- recalculation, per the SDK's explicit warning that the passed
    -- toolpath is invalid after the call.
    local failures = {}
    local recalculated_count = 0
    for _, target in ipairs(targets) do
        if not target.id_wrapper then
            table.insert(failures, target.name .. " (could not get an ID to track it - skipped)")
        else
            local find_pos = tpm:Find(target.id_wrapper.RawId)
            if find_pos == nil then
                table.insert(failures, target.name .. " (could not be found for recalculation)")
            else
                local tp = tpm:GetAt(find_pos)
                local ok, result = pcall(function() return tpm:RecalculateToolpath(tp) end)

                if not ok or not result then
                    table.insert(failures, string.format(
                        "'%s' - open the toolpath, check for errors, run Calculate if needed",
                        target.name
                    ))
                else
                    recalculated_count = recalculated_count + 1
                end
            end
        end
    end

    r:Line(string.format("  %d of %d toolpaths recalculated successfully", recalculated_count, #targets))
    for _, f in ipairs(failures) do
        r:Line("  RECALCULATION FAILED: " .. f, "error")
    end

    -- Recalculating leaves every toolpath visible in the 2D view -
    -- same cleanup as ClockReviewReport.lua, silent per its own
    -- established convention (routine gadget housekeeping, not worth
    -- announcing to an experienced instructor every run).
    pcall(function() tpm:SetAllToolpathsVisibility(false) end)
    pcall(function() job:Refresh2DView() end)

    local ok_layers, layer_manager = pcall(function() return job.LayerManager end)
    if ok_layers and layer_manager then
        local lpos = layer_manager:GetHeadPosition()
        while lpos ~= nil do
            local layer
            layer, lpos = layer_manager:GetNext(lpos)
            local ok_is_sys, is_sys = pcall(function() return layer.IsSystemLayer end)
            if ok_is_sys and is_sys then
                pcall(function() layer.Visible = false end)
            end
        end
        pcall(function() job:Refresh2DView() end)
    end

    return r
end

-- Total estimated machining time, added 2026-08-23. Two live-run
-- findings, now resolved:
--   1. The documented no-argument signature is wrong - the real
--      native call is "int MachiningTime(Toolpath const&, bool)".
--      CONFIRMED 2026-08-23: passing true vs false gave IDENTICAL
--      totals (raw=7121 both ways) on a real 4-toolpath file - the
--      bool's meaning is still undocumented, but it doesn't appear to
--      affect the result, so this just calls MachiningTime(true).
--   2. Units: CONFIRMED 2026-08-23 by Mike - raw=7121 on that same
--      job matched VCarve's own per-toolpath times summed by hand
--      (~1h58m41s) when treated as SECONDS, not minutes (the "int"
--      return type, rather than a float, was the original tip-off
--      against minutes). SECONDS is now the confirmed unit, not just
--      a plausibility guess.
function FormatTotalTimeReport(job)
    local r = NewReport()
    local tpm = ToolpathManager()

    local total_seconds = 0
    local calculated_count = 0
    local uncalculated_count = 0
    local first_failure = nil

    local pos = tpm:GetHeadPosition()
    while pos ~= nil do
        local tp
        tp, pos = tpm:GetNext(pos)
        local ok, value = pcall(function() return tp:MachiningTime(true) end)
        if ok and value then
            total_seconds = total_seconds + value
            calculated_count = calculated_count + 1
        else
            uncalculated_count = uncalculated_count + 1
            if not first_failure then
                first_failure = string.format("'%s': %s", tp.Name, tostring(value))
            end
        end
    end

    if calculated_count == 0 and tpm.Count > 0 then
        r:Line("Estimated total machining time: unknown")
    else
        local hours = math.floor(total_seconds / 3600)
        local minutes = math.floor((total_seconds % 3600) / 60)
        local seconds = math.floor(total_seconds % 60)
        local time_str
        if hours > 0 then
            time_str = string.format("%dh %02dm %02ds", hours, minutes, seconds)
        else
            time_str = string.format("%dm %02ds", minutes, seconds)
        end
        r:Line("Estimated total machining time: " .. time_str)
    end

    if uncalculated_count > 0 then
        r:Line(string.format(
            "  (%d of %d toolpaths did not return a time - may not be calculated)",
            uncalculated_count, tpm.Count
        ), "warning")
        if first_failure then
            r:Line("  DIAGNOSTIC (first failure): " .. first_failure, "warning")
        end
    end

    return r
end

function main(script_path)
    local job = VectricJob()
    if not job.Exists then
        local dialog = HTML_Dialog(false, "file:" .. script_path .. "\\" .. g_html_file, g_width, g_height, g_title)
        dialog:AddLabelField("ReportText", "No job loaded - open the student's file first.")
        dialog:ShowDialog()
        return false
    end

    local mtl_block = MaterialBlock()
    local units = mtl_block.InMM and "mm" or "inches"

    -- Recalculate every toolpath FIRST, before any other check reads
    -- toolpath statistics or machining time - see
    -- FormatToolpathRecalculationReport() for why (catches deleted-
    -- vector toolpaths VCarve's own UI won't flag) and the STANDING
    -- NOTE at the top of this file (marks the job modified - don't
    -- save over the student's original). Its own report text is
    -- appended near the end of the checks below, matching
    -- ClockReviewReport.lua's ordering, but the actual recalculation
    -- has to happen here so every later Statistics()/MachiningTime()
    -- read benefits from it.
    local recalc_report = FormatToolpathRecalculationReport(job)

    -- Total machining time - computed AFTER recalculation above, so
    -- it reflects freshly calculated toolpaths rather than whatever
    -- was saved in the student's file. See FormatTotalTimeReport()
    -- for the units caveat.
    local total_time_report = FormatTotalTimeReport(job)

    -- The FULL report: everything, in order, informational and
    -- flagged alike. Built once here and reused for both the verbose
    -- view and (filtered by severity) the compact summary below.
    local full = NewReport()
    full:Line("BOX PROJECT REVIEW REPORT v" .. g_version)
    full:Line("========================================")
    full:Line("Job: " .. job.Name)
    full:Line("Units: " .. units)
    full:Blank()
    full:Append(total_time_report)
    full:Blank()
    full:Line("MATERIAL")
    full:Line("----------------------------------------")
    full:Line(string.format(
        "  Width=%.3f  Height=%.3f  Thickness=%.3f %s",
        mtl_block.Width, mtl_block.Height, mtl_block.Thickness, units
    ))
    full:Blank()

    full:Append(FormatMaterialSetupReport(mtl_block))
    full:Append(FormatJobTypeReport(job))
    full:Append(FormatPanelGeometryReport(job))
    full:Append(FormatDogboneReport(job))
    full:Append(FormatOffsetRadiusReport(job))
    full:Append(FormatOvercutReport(job, mtl_block))
    full:Append(FormatFeedsSpeedsReport(job))
    full:Append(FormatManualPassDepthReminder())
    full:Append(FormatManualTabsReminder())
    full:Append(FormatScrewClearanceReport(job))
    full:Append(FormatUnrecognizedToolpathReport(job))
    full:Append(recalc_report)

    full:Blank()
    full:Append(FormatLayerReport(job))
    full:Append(FormatToolpathReport(job, mtl_block))

    if full.flagged then
        full:Blank()
        full:Line("*** ISSUES FLAGGED ABOVE - REVIEW BEFORE APPOINTMENT ***")
    end

    -- NOTE: job:CopyToClipboard() is NOT used (see
    -- CribbageBoardReviewReport.lua header for why - reports success but
    -- text never actually reaches the Windows clipboard). io.open()
    -- write mode is also blocked by VCarve's Lua sandbox. So: an HTML
    -- dialog (see REPORT ARCHITECTURE note at the top of this file) is
    -- the only output. It's scrollable (though not resizable), and
    -- stays compact by default, showing only the WARNINGS/ERRORS
    -- bullets rather than the full report.

    local summary = NewReport()
    summary:Line("BOX PROJECT REVIEW SUMMARY v" .. g_version)
    summary:Line("Job: " .. job.Name)
    summary:Line(string.format(
        "Material: %.3f x %.3f x %.3f %s",
        mtl_block.Width, mtl_block.Height, mtl_block.Thickness, units
    ))
    summary:Line(string.format(
        "Layers: %d   Toolpaths: %d",
        job.LayerManager.Count, ToolpathManager().Count
    ))
    -- Total machining time is always shown in the summary header,
    -- not just the flagged-bullet view below - only the informational
    -- line is copied here; any "could not compute" warning already
    -- flows into the WARNINGS bullets via full:Append(total_time_report)
    -- above.
    for _, rec in ipairs(total_time_report.records) do
        if not rec.severity then
            summary:Line(rec.text)
        end
    end

    -- Intro block never contains flagged lines, so it's always safe to
    -- render as-is via RecordsToHtml.
    local report_html = RecordsToHtml(summary.records)

    if VERBOSE_OUTPUT then
        -- Full report - everything, passing and flagged alike, colored
        -- by each record's real severity field (see REPORT ARCHITECTURE
        -- at the top of this file) rather than by searching the text
        -- for a marker substring.
        report_html = report_html .. "<br>\n" .. RecordsToHtml(full.records)
    elseif full.flagged then
        -- Compact summary: WARNINGS/ERRORS as plain bullet lists with
        -- NO severity-marker text anywhere in the displayed/copied
        -- content - see BulletSectionHtml and the REPORT ARCHITECTURE
        -- note at the top of this file.
        local warning_records = {}
        local error_records = {}
        for _, rec in ipairs(full.records) do
            if rec.severity == "warning" then
                table.insert(warning_records, rec)
            elseif rec.severity == "error" then
                table.insert(error_records, rec)
            end
        end

        if #warning_records > 0 then
            report_html = report_html .. BulletSectionHtml("WARNINGS:", warning_records, "#b35900")
        end
        if #error_records > 0 then
            report_html = report_html .. BulletSectionHtml("ERRORS:", error_records, "#b00000")
        end
    else
        report_html = report_html .. "<br>\nNo issues flagged."
    end

    local html_path = "file:" .. script_path .. "\\" .. g_html_file
    local dialog_title = g_title .. "  \226\128\148  " .. job.Name
    local dialog = HTML_Dialog(false, html_path, g_width, g_height, dialog_title)
    dialog:AddLabelField("ReportText", report_html)
    dialog:ShowDialog()

    return true
end
