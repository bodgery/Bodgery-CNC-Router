-- EXPECTED PROJECT SETUP (Box Project)
-- Source: "Box Project Instructions" (Google Doc), simplified 2026-08
-- per direct request: instead of the instructions' vague guidance
-- (measure your own stock, pick an Allowance somewhere in a range),
-- we now check against FIXED target values as if the instructions said
