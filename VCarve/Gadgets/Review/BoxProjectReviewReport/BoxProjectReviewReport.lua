--[[
  BoxProjectReviewReport.lua

  Pre-flight review checker for the "Box Project" student project
  (single-sided box built with Vectric's own "Box Creator" Gadget).
  Run from VCarve's Gadgets menu against a student's open file before
  their machine appointment.

  STANDING NOTE - DO NOT SAVE THE FILE AFTER RUNNING THIS GADGET,
  unless you specifically intend to keep whatever changed. This
  gadget runs a toolpath recalculation as part of its normal checks
  (see RECALCULATE_TOOLPATHS_TO_CHECK_ERRORS below), ported 2026-08-23
  from ClockReviewReport.lua - this is the only known way to catch a
  toolpath whose source vectors have been deleted (VCarve's own UI
  gives no visible indication of this). Running it will mark the job
  as "modified" in VCarve even when nothing was actually wrong.
  That's expected and harmless AS LONG AS you close without saving
  (or explicitly discard changes) once you're done reviewing - the
  change only exists in VCarve's in-memory session until you choose
  to save it.

  Status: TESTED end to end against a live student file (2026-08-13),
  including a real mixed warning/error run. Prior to that, individual
  check LOGIC had been hand-validated against real pasted geometry
  dumps but not run live in this exact bound form - see each check's
  own comments for that history.

  Structurally different from CribbageBoardReviewReport.lua, which this
  is NOT copied from line-for-line:
    - Box dimensions are the STUDENT'S CHOICE (no fixed width/height
      spec) - only a maximum-bound check against the supplied stock
      piece (~23.5" x 31.75") is possible.
    - Toolpaths are auto-generated by Vectric's own Box Creator Gadget,
      with student-chosen tools - there's no fixed RPM/feed/plunge
      table to check against like Cribbage Board had, so toolpaths are
      just listed for manual review, not spec-checked.
    - Single-sided job (opposite of Cribbage Board's double-sided).
    - Z-Zero should be "Machine Bed", not material surface (opposite
      of Cribbage Board) - this is important because the box-joint tabs
      are generated to match the material Thickness value EXACTLY, so
      getting that value right (student measures actual stock) matters
      a lot more here than getting Z-zero itself right, per instructions.

  KNOWN GAPS - things the instructions call out as important that this
  script does NOT check, because they'd need actual toolpath geometry
  inspection (not just top-level stats) which hasn't been attempted yet:
    (none currently open - see CLOSED GAPS below)

  CLOSED GAPS (were listed above as of 2026-08-09, now checked):
    - Dogbone presence at inside corners - see FormatDogboneReport()
    - Offset radius vs. tool radius, and dogbone spike sizing - see
      FormatOffsetRadiusReport()
    - The "Allowance" value - the SDK doesn't expose it directly, but
      it's derivable: offset_radius = 0.5*tool_diameter - allowance
      (from Box_Creator.lua's own source), and we already measure
      offset_radius and tool_radius independently, so
      allowance = tool_radius - offset_radius falls out for free.
      See FormatOffsetRadiusReport().
    - Overcut into the spoilboard - ported from CribbageBoardReviewReport.lua's
      live-tested tp:Statistics().MinimumZ mechanism. See FormatOvercutReport().
    - Whether toolpaths were hand-recreated instead of coming from the
      Box Creator gadget, or whether Box Creator was run more than
      once - see FormatUnrecognizedToolpathReport(), keyed off Box
      Creator's own fixed toolpath names (confirmed from its source).
    - Whether a toolpath's source vectors have been deleted (no other
      way to detect this - see FormatToolpathRecalculationReport(),
      ported 2026-08-23 from ClockReviewReport.lua). NOT YET LIVE-
      VALIDATED against a real Box Project file with a genuine
      deleted-vector toolpath - see that function's own comment.
    - Total estimated machining time for the job, shown in the report
      header - see FormatTotalTimeReport(). Both the missing bool
      argument and the units (seconds) were confirmed live 2026-08-23
      against a real student file - see that function's own comment.

  STILL OPEN: per-pass depths, and whether toolpath tabs are actually
  present - see FormatManualPassDepthReminder() and
  FormatManualTabsReminder() respectively for why, and what was tried.
  A 2026-08-11 investigation went deep on the tabs question specifically
  (undocumented API methods, live UI-verified controls, physical
  motion statistics, raw .crv binary analysis) and found real signal
  but nothing solid enough to automate yet - see FormatManualTabsReminder()
  for a summary and Gadgets/Diagnostics/ for the exploratory scripts if
  this gets picked up again.

  ASSUMPTION TO VERIFY LIVE: this assumes MaterialBlock.Z_BOTTOM
  corresponds to the Job Setup dialog's "Machine Bed" option. This
  worked cleanly for Cribbage Board's Z_TOP = "Top of Material" (exact
  wording match), but "Machine Bed" is different wording than "Bottom
  of Material" in the SDK enum, so this mapping is NOT confirmed.

  REPORT ARCHITECTURE - rewritten 2026-08-13, replacing the original
  "!!"/"~~" TEXT MARKER design. Ported from CribbageBoardReviewReport.lua
  after that gadget's own rewrite was built, tested (25 unit tests plus
  a live mixed warning/error run), and confirmed. Full rationale lives
  there; short version: severity used to be a literal substring ("!!"
  or "~~") glued onto the front of a message's text, and every consumer
  had to search the text for it. "~~" is ALSO Markdown strikethrough
  syntax, and a real Windows clipboard conversion step during copy/
  paste treated two separate, unrelated "~~" lines anywhere in the same
  copied selection as an opening/closing PAIR, corrupting (on one real
  test, swallowing dozens of lines of) the copied text. Every
  Format*Report() function below now returns a Report object (see
  NewReport()) instead of a concatenated string: an ordered list of
  {text=, severity=} records, where severity is a real Lua value (nil /
  "warning" / "error"), never text - there is nothing for a Markdown-
  aware (or any other) text-processing step to misinterpret, regardless
  of marker choice. Reports also track their own .flagged state
  automatically, so main() no longer needs a pile of separately-tracked
  *_flagged locals ORed together.

  What it reports, for the currently open job:
    1. Job name + units, and total estimated machining time in
       hours/minutes/seconds (summed across every toolpath via
       Toolpath:MachiningTime(true), computed AFTER the toolpath
       recalculation described below)
    2. Material width/height vs. the supplied stock's maximum bounds
       (~23.5" x 31.75", checked in either orientation since the
       instructions don't specify an axis mapping for this project)
    3. Material thickness vs. a plausible "measured 1/2" plywood" range
       - NOT a strict spec (thickness is student-measured, correctly
       varies a bit), just a sanity check against a totally wrong or
       leftover value (e.g. a stale 0.75" from a different project) -
       plus a separate "exactly the Box Creator default" check
    4. Z-Zero (should be Machine Bed per instructions - see assumption above)
    5. Job type (should be single-sided)
    6. Panel geometry, dogbone presence/sizing, offset radius/Allowance,
       overcut into the spoilboard, feeds/speeds, screw clearance,
       unrecognized/duplicate toolpaths - see each check's own comments
    7. Toolpath recalculation (see STANDING NOTE at the top of this
       file) - catches a toolpath whose source vectors have been
       deleted, which VCarve's own UI gives no indication of
    8. Every layer: name, object count, visible/locked
    9. Every toolpath: name, tool name/diameter/number, feeds/speeds
       (listed for manual review - no spec table to check against)
]]

