-- Compares a toolpath's actual tool params against a spec's expected
-- values (any expected field left nil skips that particular check).
-- rpm is unitless (rotational) so compared directly; feed/plunge/dia are
-- lengths, converted to job units via ToJobUnits before comparing, same
-- as every other check in this file. Returns a list of PLAIN mismatch
-- strings (empty if everything matches) - callers tag these "error"
-- when adding them to a Report, same pattern as
-- CribbageBoardReviewReport.lua's CheckToolParams.
--
-- Aggressive-settings detection, added 2026-08-10: if feed/plunge don't
-- match the expected (through-cut) values, check whether they instead
-- match the AGGRESSIVE values before falling back to a generic mismatch
-- message - gives a precise, actionable message for a specific, likely
-- mistake (using aggressive settings for what should be a conservative
-- through-cut) rather than just "wrong number".
--
-- NOTE on per-pass depths: Box_Cut_Out's actual pass depths (the list a
-- student can individually edit via VCarve's "Specify Pass Depths"
-- dialog, opened from the Profile toolpath form's "Edit Passes" button)
-- are DELIBERATELY NOT CHECKED HERE - see FormatManualPassDepthReminder()
-- below for why and what to do about it instead.
function CheckToolParams(tool, spec, mtl_block)
    local mismatches = {}
    if not tool then
        table.insert(mismatches, "no tool assigned")
        return mismatches
    end

    local units = mtl_block.InMM and "mm" or "inches"

    if spec.rpm_expected and math.abs(tool.SpindleSpeed - spec.rpm_expected) > spec.rpm_tolerance then
        table.insert(mismatches, string.format(
            "RPM expected=%.0f actual=%.0f", spec.rpm_expected, tool.SpindleSpeed
        ))
    end
    if spec.feed_expected_in then
        local feed_expected = ToJobUnits(spec.feed_expected_in, mtl_block)
        local feed_tolerance = ToJobUnits(spec.feed_tolerance_in, mtl_block)
        if math.abs(tool.FeedRate - feed_expected) > feed_tolerance then
            local matches_aggressive = false
            if spec.aggressive_feed_in then
                local aggressive_feed = ToJobUnits(spec.aggressive_feed_in, mtl_block)
                matches_aggressive = math.abs(tool.FeedRate - aggressive_feed) <= feed_tolerance
            end
            if matches_aggressive then
                table.insert(mismatches, string.format(
                    "feed=%.1f %s/min matches AGGRESSIVE settings - not appropriate for a through-cut, expected %.1f",
                    tool.FeedRate, units, feed_expected
                ))
            else
                table.insert(mismatches, string.format(
                    "feed expected=%.1f actual=%.1f %s/min", feed_expected, tool.FeedRate, units
                ))
            end
        end
    end
    if spec.plunge_expected_in then
        local plunge_expected = ToJobUnits(spec.plunge_expected_in, mtl_block)
        local plunge_tolerance = ToJobUnits(spec.plunge_tolerance_in, mtl_block)
        if math.abs(tool.PlungeRate - plunge_expected) > plunge_tolerance then
            local matches_aggressive = false
            if spec.aggressive_plunge_in then
                local aggressive_plunge = ToJobUnits(spec.aggressive_plunge_in, mtl_block)
                matches_aggressive = math.abs(tool.PlungeRate - aggressive_plunge) <= plunge_tolerance
            end
            if matches_aggressive then
                table.insert(mismatches, string.format(
                    "plunge=%.1f %s/min matches AGGRESSIVE settings - not appropriate for a through-cut, expected %.1f",
                    tool.PlungeRate, units, plunge_expected
                ))
            else
                table.insert(mismatches, string.format(
                    "plunge expected=%.1f actual=%.1f %s/min", plunge_expected, tool.PlungeRate, units
                ))
            end
        end
    end
    -- Max-pass-depth check is disabled - see comment block above
    -- CheckToolParams for why (no working SDK access found after
    -- thorough live testing on 2026-08-10).

    -- Per-pass depths are NOT checked here - see
    -- FormatManualPassDepthReminder() for why.

    return mismatches
end

