-- Shared toolpath-by-name lookup, factored out of FormatOffsetRadiusReport
-- 2026-08 since this check needs the exact same thing: find the tool
-- assigned to a specific named toolpath, falling back to the first
-- toolpath if the student renamed it away from Box Creator's default.
function FindToolByToolpathName(expected_name)
    local tpm = ToolpathManager()
    local found_tool = nil
    local renamed_fallback_note = nil

    local tp_pos = tpm:GetHeadPosition()
    while tp_pos ~= nil do
        local tp
        tp, tp_pos = tpm:GetNext(tp_pos)
        if tp.Name == expected_name then
            found_tool = tp.Tool
        end
    end

    if not found_tool and tpm.Count > 0 then
        local tp_pos2 = tpm:GetHeadPosition()
        local tp
        tp, tp_pos2 = tpm:GetNext(tp_pos2)
        found_tool = tp.Tool
        renamed_fallback_note = "no toolpath named '" .. expected_name .. "' - using first toolpath's tool instead"
    end

    return found_tool, renamed_fallback_note
end

function FormatFeedsSpeedsReport(job)
    local r = NewReport()
    local mtl_block = MaterialBlock()
    local units = mtl_block.InMM and "mm" or "inches"

    r:Blank()
    r:Header("FEEDS/SPEEDS CHECK (Box_Cut_Out)")

    local tool, fallback_note = FindToolByToolpathName("Box_Cut_Out")
    if fallback_note then
        r:Line("  Note: " .. fallback_note)
    end

    if not tool then
        r:Line("  No toolpath/tool found - cannot check feeds/speeds", "error")
        return r
    end

    -- ConvertUnitsFrom in Box_Creator.lua's own source converts the
    -- tool's diameter into the job's units before using it - do the same
    -- here rather than assume tool.ToolDia is already in job units.
    local tool_dia = tool.ToolDia
    if tool.InMM ~= mtl_block.InMM then
        if tool.InMM then
            tool_dia = tool_dia / INCHES_TO_MM
        else
            tool_dia = tool_dia * INCHES_TO_MM
        end
    end

    r:Line(string.format(
        "  Tool: '%s' dia=%.3f %s   RPM=%.0f feed=%.1f plunge=%.1f",
        tool.Name, tool_dia, units, tool.SpindleSpeed, tool.FeedRate, tool.PlungeRate
    ))

    local matched_spec = nil
    for _, spec in ipairs(BOX_CUTOUT_FEEDS_SPEEDS) do
        local dia_expected = ToJobUnits(spec.tool_dia_expected_in, mtl_block)
        local dia_tolerance = ToJobUnits(spec.tool_dia_tolerance_in, mtl_block)
        if math.abs(tool_dia - dia_expected) <= dia_tolerance then
            matched_spec = spec
            break
        end
    end

    if not matched_spec then
        r:Line(string.format(
            "  NO VALIDATED FEEDS/SPEEDS for a %.3f %s bit - verify manually against the feeds/speeds cheat sheet, or test and add this size to BOX_CUTOUT_FEEDS_SPEEDS",
            tool_dia, units
        ), "error")
        return r
    end

    r:Line("  Matched spec: " .. matched_spec.label)
    local mismatches = CheckToolParams(tool, matched_spec, mtl_block)
    for _, m in ipairs(mismatches) do
        r:Line("  " .. m, "error")
    end
    if #mismatches == 0 then
        r:Line("  Feeds/speeds match")
    end

    return r
end

-- Overcut check, added 2026-08, ported directly from
-- CribbageBoardReviewReport.lua's proven, live-tested mechanism (it
-- caught a real overcut error on a real student file). Uses the same
-- tp:Statistics().MinimumZ + mtl_block:CalcDepthFromAbsoluteZ() pattern -
-- that conversion method correctly handles either Z-zero setting
-- (Cribbage's "Top of Material" or Box's "Machine Bed"), so it needed
-- no adaptation.
--
-- Target confirmed directly by Mike (2026-08-10): 0.020" into the
-- spoilboard, same number as Cribbage Board's final part cutout - not
-- assumed to carry over, asked and confirmed before building this.
OVERCUT_TARGET_IN = 0.020  -- inches into the spoilboard
OVERCUT_TOLERANCE_IN = 0.010  -- inches - "small variations are acceptable" per Mike

-- Float slack on the tolerance comparison (2026-10-14, v0.10.0).
-- Overcut = depth - thickness, both floats, so a value meant to sit
-- exactly on the tolerance edge (e.g. 0.010") can compute as
-- 0.0099999..., print as "0.0100", and still fail - a real false
-- positive seen on a Box Project file under v0.9.0. 0.001" per Mike:
-- physically negligible for spoilboard overcut.
BOUNDARY_EPSILON_IN = 0.001  -- inches

function FormatOvercutReport(job, mtl_block)
    local r = NewReport()
    local units = mtl_block.InMM and "mm" or "inches"
    local overcut_target = ToJobUnits(OVERCUT_TARGET_IN, mtl_block)
    local overcut_tolerance = ToJobUnits(OVERCUT_TOLERANCE_IN, mtl_block)
    local boundary_epsilon = ToJobUnits(BOUNDARY_EPSILON_IN, mtl_block)

    r:Blank()
    r:Header("OVERCUT CHECK (Box_Cut_Out)")

    local tpm = ToolpathManager()
    local target_tp = nil
    local pos = tpm:GetHeadPosition()
    while pos ~= nil do
        local tp
        tp, pos = tpm:GetNext(pos)
        if tp.Name == "Box_Cut_Out" then
            target_tp = tp
        end
    end
    if not target_tp and tpm.Count > 0 then
        local pos2 = tpm:GetHeadPosition()
        target_tp = tpm:GetNext(pos2)
        r:Line("  Note: no toolpath named 'Box_Cut_Out' - using first toolpath instead")
    end

    if not target_tp then
        r:Line("  No toolpath found - cannot check overcut", "error")
        return r
    end

    local ok_stats, stats = pcall(function() return target_tp:Statistics() end)
    if not ok_stats or not stats or not stats.IsValid then
        r:Line("  Could not read toolpath statistics - cannot check overcut", "error")
        return r
    end

    local depth = mtl_block:CalcDepthFromAbsoluteZ(stats.MinimumZ)
    local overcut = depth - mtl_block.Thickness

    r:Line(string.format(
        "  Cut depth: %.4f %s   Material thickness: %.4f %s   Overcut: %.4f %s",
        depth, units, mtl_block.Thickness, units, overcut, units
    ))

    if math.abs(overcut - overcut_target) > overcut_tolerance + boundary_epsilon then
        if overcut <= 0 then
            r:Line(string.format(
                "  NO OVERCUT: overcut=%.4f %s, target=%.3f %s",
                overcut, units, overcut_target, units
            ), "error")
        else
            r:Line(string.format(
                "  OVERCUT OUT OF RANGE: %.4f %s (target %.3f +/- %.3f %s)",
                overcut, units, overcut_target, overcut_tolerance, units
            ), "error")
        end
    end

    return r
end

-- Screw clearance check, added 2026-08. Workpiece is held with 4 screws,
-- one near each corner of the stock, inset 0.75" from each edge. Mike
-- wants the toolpath geometry (before tool-radius overhang) kept a
-- further 0.75" clear of the screw position, so the toolpath's design
-- line must stay >= 1.5" from the stock edges, and the ACTUAL swept cut
-- (toolpath expanded by tool_radius, since the spinning bit's body
-- reaches that far beyond the path in every direction) must too.
--
-- Screw positions aren't drawn as CAD geometry anywhere in the file
-- (they're a physical fixturing detail, not part of the design), so
-- there's no way to check clearance against the actual screw locations
-- directly. This checks the more conservative proxy Mike described
-- instead: the swept CutOut-layer bounding box must clear ALL FOUR
-- sides of the material bounding box by the required margin, not just
-- near the corners specifically - stricter than strictly necessary
-- everywhere except near the corners (where it's exactly what's needed),
-- but doesn't require guessing where along an edge a screw might be.
REQUIRED_SCREW_MARGIN_IN = 1.5  -- inches (0.75 screw inset + 0.75 extra safety, per Mike)
SCREW_MARGIN_TOLERANCE_IN = 0.01  -- inches

-- Compute the material's bounding box in the same absolute coordinate
-- frame as CAD geometry, accounting for wherever Job Setup's XY origin
-- is set. Mapping confirmed live via CribbageBoardReviewReport.lua's
-- XY-origin check (BLC/BRC/TRC/TLC/CENTRE) - reused here, generalized to
-- return actual (MinX,MinY,MaxX,MaxY) rather than just a display string,
-- since Box Project's instructions don't specify a required origin (no
-- flag if it's not centred - unlike Cribbage - just used to correctly
-- locate the material bounds for this check).
function GetMaterialBoundingBox(mtl_block)
    local w, h = mtl_block.Width, mtl_block.Height
    local origin = mtl_block.XYOrigin
    if origin == MaterialBlock.BLC then
        return 0, 0, w, h
    elseif origin == MaterialBlock.BRC then
        return -w, 0, 0, h
    elseif origin == MaterialBlock.TRC then
        return -w, -h, 0, 0
    elseif origin == MaterialBlock.TLC then
        return 0, -h, w, 0
    else  -- MaterialBlock.CENTRE, or unrecognized - CENTRE is the most
          -- common default, so fall back to it rather than error out
        return -w / 2, -h / 2, w / 2, h / 2
    end
end

function FormatScrewClearanceReport(job)
    local r = NewReport()
    local mtl_block = MaterialBlock()
    local units = mtl_block.InMM and "mm" or "inches"
    local required_margin = ToJobUnits(REQUIRED_SCREW_MARGIN_IN, mtl_block)
    local margin_tolerance = ToJobUnits(SCREW_MARGIN_TOLERANCE_IN, mtl_block)

    r:Blank()
    r:Header("SCREW CLEARANCE CHECK (CutOut layer)")

    local layer = job.LayerManager:FindLayerWithName("CutOut")
    if not layer then
        r:Line("  No layer named 'CutOut' found - cannot check screw clearance", "error")
        return r
    end

    -- Aggregate bounding box of all CutOut geometry (the toolpath's
    -- actual design line, before tool-radius overhang)
    local agg_min_x, agg_min_y, agg_max_x, agg_max_y = nil, nil, nil, nil
    local pos = layer:GetHeadPosition()
    while pos ~= nil do
        local obj
        obj, pos = layer:GetNext(pos)
        local ok, contour = pcall(function() return obj:GetContour() end)
        if ok and contour then
            local bbox = contour.BoundingBox2D
            if agg_min_x == nil then
                agg_min_x, agg_min_y, agg_max_x, agg_max_y = bbox.MinX, bbox.MinY, bbox.MaxX, bbox.MaxY
            else
                agg_min_x = math.min(agg_min_x, bbox.MinX)
                agg_min_y = math.min(agg_min_y, bbox.MinY)
                agg_max_x = math.max(agg_max_x, bbox.MaxX)
                agg_max_y = math.max(agg_max_y, bbox.MaxY)
            end
        end
    end

    if agg_min_x == nil then
        r:Line("  No geometry found on 'CutOut' layer - cannot check screw clearance", "error")
        return r
    end

    -- Expand by tool radius - the actual swept cut extent, not just the
    -- toolpath's design line
    local cutout_tool, fallback_note = FindToolByToolpathName("Box_Cut_Out")
    if fallback_note then
        r:Line("  Note: " .. fallback_note)
    end
    if not cutout_tool then
        r:Line("  No toolpath/tool found - cannot account for bit overhang, checking design line only (less conservative)", "error")
    end

    local tool_radius = 0
    if cutout_tool then
        local tool_dia = cutout_tool.ToolDia
        if cutout_tool.InMM ~= mtl_block.InMM then
            if cutout_tool.InMM then
                tool_dia = tool_dia / INCHES_TO_MM
            else
                tool_dia = tool_dia * INCHES_TO_MM
            end
        end
        tool_radius = 0.5 * tool_dia
    end

    local swept_min_x = agg_min_x - tool_radius
    local swept_min_y = agg_min_y - tool_radius
    local swept_max_x = agg_max_x + tool_radius
    local swept_max_y = agg_max_y + tool_radius

    local mat_min_x, mat_min_y, mat_max_x, mat_max_y = GetMaterialBoundingBox(mtl_block)

    r:Line(string.format(
        "  Material bounds: (%.3f, %.3f) to (%.3f, %.3f) %s",
        mat_min_x, mat_min_y, mat_max_x, mat_max_y, units
    ))
    r:Line(string.format(
        "  Swept cut bounds: (%.3f, %.3f) to (%.3f, %.3f) %s (tool radius %.3f %s)",
        swept_min_x, swept_min_y, swept_max_x, swept_max_y, units, tool_radius, units
    ))

    local margin_left = swept_min_x - mat_min_x
    local margin_bottom = swept_min_y - mat_min_y
    local margin_right = mat_max_x - swept_max_x
    local margin_top = mat_max_y - swept_max_y

    r:Line(string.format(
        "  Margins: left=%.3f bottom=%.3f right=%.3f top=%.3f %s (required %.2f %s)",
        margin_left, margin_bottom, margin_right, margin_top, units, required_margin, units
    ))

    local margins = {
        { name = "left", value = margin_left },
        { name = "bottom", value = margin_bottom },
        { name = "right", value = margin_right },
        { name = "top", value = margin_top },
    }
    for _, m in ipairs(margins) do
        if m.value < required_margin - margin_tolerance then
            r:Line(string.format(
                "  %s MARGIN TOO SMALL: %.3f %s (need %.2f %s) - toolpath may hit a hold-down screw",
                m.name, m.value, units, required_margin, units
            ), "error")
        end
    end

    return r
end

-- Unrecognized/duplicate toolpath detection, added 2026-08. Closes a
-- KNOWN GAP from the header: whether toolpaths were hand-recreated
-- instead of coming from Box Creator, or whether Box Creator was run
-- more than once. Confirmed directly by Mike (2026-08-10): Box Creator
-- is NOT idempotent - if a student changes their mind on a parameter,
-- their instinct is to just run it again, which does NOT clean up the
-- previous run's geometry/toolpaths first.
--
-- Adapted from Cribbage Board's "unrecognized toolpath" concept, but
-- simpler here: Box Creator always uses the SAME fixed toolpath names
-- (Box_Cut_Out, Box_Dovetail, Box_Lid_Pocket - confirmed directly from
-- Box_Creator.lua's own source, not guessed), unlike Cribbage's 7
-- operations which needed side+depth fingerprinting because names
-- weren't reliable. So this only needs a name membership + count check:
--   - any toolpath whose name ISN'T one of the 3 known names -> flagged
--     UNRECOGNIZED (catches both a hand-made toolpath, and a second
--     Box Creator run if VCarve auto-suffixes the repeat name)
--   - any known name appearing MORE THAN ONCE -> flagged DUPLICATE
--     (catches a second run if VCarve instead allows the exact same
--     name to repeat)
-- Covers both possible behaviors since it's not confirmed which one
-- VCarve actually does on a second Box Creator run - safer to check
-- for both than assume.
KNOWN_BOX_TOOLPATH_NAMES = { "Box_Cut_Out", "Box_Dovetail", "Box_Lid_Pocket" }

function FormatUnrecognizedToolpathReport(job)
    local r = NewReport()
    r:Blank()
    r:Header("UNRECOGNIZED/DUPLICATE TOOLPATH CHECK")

    local known_set = {}
    for _, name in ipairs(KNOWN_BOX_TOOLPATH_NAMES) do
        known_set[name] = true
    end

    local name_counts = {}
    local unrecognized = {}

    local tpm = ToolpathManager()
    local pos = tpm:GetHeadPosition()
    while pos ~= nil do
        local tp
        tp, pos = tpm:GetNext(pos)
        if known_set[tp.Name] then
            name_counts[tp.Name] = (name_counts[tp.Name] or 0) + 1
        else
            table.insert(unrecognized, tp.Name)
        end
    end

    for _, name in ipairs(unrecognized) do
        r:Line(string.format(
            "  UNRECOGNIZED TOOLPATH: '%s' - not one of Box Creator's own names (%s) - check for a hand-made toolpath or a re-run of Box Creator",
            name, table.concat(KNOWN_BOX_TOOLPATH_NAMES, ", ")
        ), "error")
    end

    for _, name in ipairs(KNOWN_BOX_TOOLPATH_NAMES) do
        local count = name_counts[name] or 0
        if count > 1 then
            r:Line(string.format(
                "  DUPLICATE TOOLPATH: '%s' appears %d times - Box Creator was likely run more than once",
                name, count
            ), "error")
        end
    end

    if not r.flagged then
        r:Line("  All toolpath names recognized, no duplicates")
    end

    return r
end

