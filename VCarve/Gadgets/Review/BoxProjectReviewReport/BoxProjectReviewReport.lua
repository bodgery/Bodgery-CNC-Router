-- All threshold/tolerance constants below are defined in INCHES (the
-- unit this file and the class instructions were originally written
-- in). Students may set their job to mm instead, so EVERY comparison
-- in this file converts these inches values to the job's actual units
-- via ToJobUnits() before comparing - this applies uniformly across
-- every check now, not just one.
INCHES_TO_MM = 25.4

function ToJobUnits(value_inches, mtl_block)
    if mtl_block.InMM then
        return value_inches * INCHES_TO_MM
    end
    return value_inches
end

-- Supplied stock piece is ~23.5" x 31.75" x 0.5" - students choose
-- their own box size, so this is a MAXIMUM BOUND check, not an exact
-- match. Checked in either orientation since the instructions don't
-- specify which axis is which for this project (unlike Cribbage
-- Board, which explicitly stated long dimension = X).
MAX_STOCK_DIM_LONG_IN  = 31.75  -- inches
MAX_STOCK_DIM_SHORT_IN = 23.5   -- inches
STOCK_DIM_TOLERANCE_IN = 0.1    -- inches - small margin for cutting/kerf

-- Nominal supplied stock thickness is 1/2" plywood, but the
-- instructions are explicit that students should MEASURE their actual
-- stock and use the largest value found, so this is a plausibility
-- check (catches a wildly wrong or stale value), not a strict spec.
NOMINAL_THICKNESS_IN      = 0.50  -- inches
THICKNESS_PLAUSIBLE_TOL_IN = 0.05  -- inches

-- Allowance (clearance) target, simplified per 2026-08 request to a
-- single fixed value - Mike's own preferred setting from the
-- instructions doc's "Tips and Tricks" section: 0.20mm (0.010").
-- We derive the actual Allowance used indirectly (see
-- FormatOffsetRadiusReport) since it isn't exposed directly by the SDK.
ALLOWANCE_TARGET_IN    = 0.010  -- inches (= 0.20mm)
ALLOWANCE_TOLERANCE_IN = 0.002  -- inches

-- Set to true to see the FULL report (every layer, every toolpath,
-- all passing checks included) instead of just the flagged issues.
-- No separate gadget needed - flip this, save, and re-run the same
-- gadget from the menu. Flip back to false afterward to go back to
-- the compact summary. The dialog is scrollable, so full mode is
-- usable for spot-checking, just longer to scroll through.
VERBOSE_OUTPUT = false

function FormatMaterialSetupReport(mtl_block)
    local r = NewReport()
    local units = mtl_block.InMM and "mm" or "inches"

    r:Header("MATERIAL SETUP CHECKS")

    -- Stock size vs. supplied piece - max bound, either orientation.
    -- Thresholds converted to the job's actual units (see ToJobUnits).
    local max_stock_long = ToJobUnits(MAX_STOCK_DIM_LONG_IN, mtl_block)
    local max_stock_short = ToJobUnits(MAX_STOCK_DIM_SHORT_IN, mtl_block)
    local stock_tol = ToJobUnits(STOCK_DIM_TOLERANCE_IN, mtl_block)
    local stock_short = math.min(mtl_block.Width, mtl_block.Height)
    local stock_long = math.max(mtl_block.Width, mtl_block.Height)
    if stock_short > max_stock_short + stock_tol
       or stock_long > max_stock_long + stock_tol then
        r:Line(string.format(
            "  STOCK SIZE EXCEEDS SUPPLIED PIECE: %.3f x %.3f %s (max %.2f x %.2f %s)",
            mtl_block.Width, mtl_block.Height, units, max_stock_short, max_stock_long, units
        ), "error")
    end

    -- Thickness plausibility - NOT a strict spec, students measure
    -- their own stock. Only flags values far from the nominal 1/2",
    -- which likely means an unmeasured/stale/default value.
    local nominal_thickness = ToJobUnits(NOMINAL_THICKNESS_IN, mtl_block)
    local thickness_plausible_tol = ToJobUnits(THICKNESS_PLAUSIBLE_TOL_IN, mtl_block)
    local thickness_diff = mtl_block.Thickness - nominal_thickness
    if math.abs(thickness_diff) > thickness_plausible_tol then
        r:Line(string.format(
            "  THICKNESS UNUSUAL: nominal=%.3f actual=%.3f %s",
            nominal_thickness, mtl_block.Thickness, units
        ), "error")
    end

    -- Exact-default detection - separate from the plausibility check
    -- above. Real measured stock essentially never comes out to EXACTLY
    -- 0.500" - a value this precise almost always means the student
    -- left the Box Creator's default in place and never measured their
    -- actual material. This matters more here than a normal "unusual
    -- value" flag: since Box Creator generates joint tabs sized to
    -- match Thickness exactly, fixing this after the fact means the
    -- student must delete ALL toolpaths and re-run Box Creator (or
    -- start a new file) with the corrected value - not something to
    -- discover for the first time at the machine appointment.
    -- Tight epsilon (not thickness_plausible_tol) because we're
    -- detecting "suspiciously exact", not "suspiciously different".
    local exact_default_epsilon = ToJobUnits(0.0005, mtl_block)  -- float-safe equality
    if math.abs(thickness_diff) < exact_default_epsilon then
        r:Line(string.format(
            "  THICKNESS IS EXACTLY %.3f %s (the Box Creator default)",
            nominal_thickness, units
        ), "warning")
    end

    -- Z-zero: should be Machine Bed, NOT material surface (opposite
    -- of Cribbage Board). ASSUMPTION UNVERIFIED - see header note.
    local z_origin = mtl_block.ZOrigin
    local z_origin_text = "unknown"
    if z_origin == MaterialBlock.Z_TOP then
        z_origin_text = "Top of Material"
    elseif z_origin == MaterialBlock.Z_CENTRE then
        z_origin_text = "Centre of Material"
    elseif z_origin == MaterialBlock.Z_BOTTOM then
        z_origin_text = "Bottom of Material (assumed = Machine Bed - UNVERIFIED, correct)"
    end
    r:Line("  Z-Zero: " .. z_origin_text)
    if z_origin ~= MaterialBlock.Z_BOTTOM then
        r:Line("  Z-ZERO should be Machine Bed, is " .. z_origin_text, "error")
    end

    -- XY-origin: MUST be Bottom Left Corner. Confirmed directly by Mike
    -- (2026-08-10): Box Creator's own layout math assumes BLC and draws
    -- vectors in the wrong place under any other origin - not a style
    -- preference like Cribbage Board's Centre requirement, an actual
    -- correctness dependency in Box_Creator.lua itself.
    local xy_origin = mtl_block.XYOrigin
    local xy_origin_text = "unknown"
    if xy_origin == MaterialBlock.BLC then
        xy_origin_text = "Bottom Left Corner (correct)"
    elseif xy_origin == MaterialBlock.BRC then
        xy_origin_text = "Bottom Right Corner"
    elseif xy_origin == MaterialBlock.TRC then
        xy_origin_text = "Top Right Corner"
    elseif xy_origin == MaterialBlock.TLC then
        xy_origin_text = "Top Left Corner"
    elseif xy_origin == MaterialBlock.CENTRE then
        xy_origin_text = "Centre"
    end
    r:Line("  XY-Origin: " .. xy_origin_text)
    if xy_origin ~= MaterialBlock.BLC then
        r:Line("  XY-ORIGIN should be Bottom Left Corner, is " .. xy_origin_text, "error")
    end

    return r
end

function FormatJobTypeReport(job)
    local r = NewReport()
    r:Blank()
    r:Header("JOB TYPE CHECK")

    -- Opposite of Cribbage Board - Box Project is single-sided.
    if not job.IsDoubleSided then
        r:Line("  Job type: Single-Sided (correct)")
    else
        r:Line("  JOB TYPE: expected Single-Sided, is two-sided", "error")
    end

    return r
end

-- Panel geometry check, added 2026-08 after live debugging against a real
-- student file (see chat history: DebugDump.lua / ClassifyTest.lua gadgets).
--
-- STATUS: the pairing/dimension-derivation LOGIC below was hand-validated
-- against a real pasted geometry dump from a real student file and gave
-- correct results (12x7x4 box, 3 correct pairs), and confirmed again in
-- the 2026-08-13 live test run.
--
-- Why this operates on the "Box" layer, not "CutOut": "Box" holds the
-- un-offset joint-cut vectors (Box Creator's actual design geometry).
-- "CutOut" is the toolpath-preview layer, offset outward by the cutter
-- radius for actual machining - its bounding boxes are consistently a bit
-- larger (e.g. 12.105 vs 12.0 was seen in real data) and would throw off
-- exact-match pairing. If "Box" isn't found, this check is skipped, not
-- silently run against the wrong layer.
--
-- Why bounding boxes, not per-edge tab/dovetail classification: an earlier
-- approach tried to classify each panel edge as tab/socket by geometry, but
-- box joints are proud (tab) on one panel and recessed (socket) on the
-- mating panel at the SAME corner - which side is which alternates by
-- design, so there's no fixed per-edge rule to detect. Bounding box pairing
-- sidesteps this entirely: it doesn't care about the joint pattern, only
-- the panel's overall footprint, which is unaffected by which side of each
-- corner is proud or recessed.
DIM_GROUP_TOLERANCE_IN = 0.02  -- inches - panels pair up if within this of each other

function FormatPanelGeometryReport(job)
    local r = NewReport()
    local mtl_block = MaterialBlock()
    local dim_group_tolerance = ToJobUnits(DIM_GROUP_TOLERANCE_IN, mtl_block)

    r:Blank()
    r:Header("PANEL GEOMETRY (Box layer)")

    local layer = job.LayerManager:FindLayerWithName("Box")
    if not layer then
        r:Line("  No layer named 'Box' found - cannot check panel geometry", "error")
        return r
    end

    -- Collect each panel's (short, long) bounding-box dimensions
    local panels = {}
    local pos = layer:GetHeadPosition()
    while pos ~= nil do
        local obj
        obj, pos = layer:GetNext(pos)
        local ok, contour = pcall(function() return obj:GetContour() end)
        if ok and contour then
            local bbox = contour.BoundingBox2D
            local short = math.min(bbox.XLength, bbox.YLength)
            local long = math.max(bbox.XLength, bbox.YLength)
            table.insert(panels, { short = short, long = long, used = false })
        end
    end

    r:Line(string.format("  Panel count: %d", #panels))
    if #panels == 0 then
        r:Line("  No panels with contours found on 'Box' layer", "error")
        return r
    end

    -- Group panels into matching pairs by (short, long), within tolerance
    local groups = {}  -- each: { short=, long=, count= }
    for i = 1, #panels do
        if not panels[i].used then
            local group = { short = panels[i].short, long = panels[i].long, count = 1 }
            panels[i].used = true
            for j = i + 1, #panels do
                if not panels[j].used
                   and math.abs(panels[j].short - group.short) < dim_group_tolerance
                   and math.abs(panels[j].long - group.long) < dim_group_tolerance then
                    group.count = group.count + 1
                    panels[j].used = true
                end
            end
            table.insert(groups, group)
        end
    end

    r:Line(string.format("  Distinct panel sizes found: %d", #groups))
    for i, g in ipairs(groups) do
        if g.count ~= 2 then
            r:Line(string.format(
                "    %.3f x %.3f  (x%d) - expected 2", g.short, g.long, g.count
            ), "error")
        else
            r:Line(string.format("    %.3f x %.3f  (x%d)", g.short, g.long, g.count))
        end
    end

    -- Derive box W/D/H: each dimension value should appear in exactly 2 of
    -- the 3 panel-size groups (bottom/lid share W&D, sides share W&H, ends
    -- share D&H). A complete box has exactly 3 groups; fewer is legitimate
    -- if the student unchecked a face (e.g. no lid) in Box Creator.
    if #groups == 3 then
        local value_counts = {}
        local function record(v)
            local key = string.format("%.3f", v)
            value_counts[key] = (value_counts[key] or 0) + 1
        end
        for _, g in ipairs(groups) do
            record(g.short)
            record(g.long)
        end
        local dims = {}
        local consistent = true
        for key, count in pairs(value_counts) do
            if count == 2 then
                table.insert(dims, tonumber(key))
            else
                consistent = false
            end
        end
        if consistent and #dims == 3 then
            table.sort(dims, function(a, b) return a > b end)
            r:Line(string.format(
                "  Derived box dimensions: %.3f x %.3f x %.3f",
                dims[1], dims[2], dims[3]
            ))
        else
            r:Line("  Panel sizes don't chain into consistent box dimensions", "error")
        end
    elseif #groups < 3 then
        r:Line(string.format(
            "  Note: only %d panel-size group(s) found (expected 3 for a full box - fewer is OK if student unchecked a face in Box Creator, e.g. no lid)",
            #groups
        ))
    else
        r:Line("  More than 3 distinct panel sizes - check for stray/duplicate geometry", "error")
    end

    return r
end

-- Dogbone relief detection, added 2026-08. This closes one of the
-- KNOWN GAPS listed in the file header ("whether dogbones are actually
-- present at inside corners").
--
-- STATUS: the detection signature below was validated against real
-- pasted CutOut-layer geometry, and confirmed again in the 2026-08-13
-- live test run. Real example that confirmed the signature:
--   Span 3: LINE start=(1.6975,14.6975) end=(1.7129,14.7129)
--   Span 4: LINE start=(1.7129,14.7129) end=(1.6975,14.6975)
-- Span 4 ends exactly where span 3 started - a short "there and back"
-- spike. This matches the CreateDogboneProfile/ComputeDogBones function
-- names seen in Box_Creator.lua's own source, so this pattern is very
-- likely the actual dogbone relief cut, not a coincidental artifact.
--
-- Why "CutOut" layer, not "Box": dogbones are a toolpath-compensation
-- feature (relief for the round bit at inside corners) - they exist only
-- in the offset/machining geometry, not the raw design vectors.
--
-- SPIKE_MAX_LENGTH is a generic threshold, not derived from tool
-- diameter or material thickness (neither is reliably available/relevant
-- here) - chosen to comfortably separate spikes (~0.02" in the real
-- example above) from normal tab-edge segments (~0.4"+ in the same
-- data). Fine for a presence/absence check; would need tightening if this
-- was ever used to validate spike SIZE against a specific tool radius.
SPIKE_MAX_LENGTH_IN = 0.10  -- inches
SPIKE_RETURN_TOLERANCE_IN = 0.005  -- inches - how close is "returns to start"

local function PointDist(p1, p2)
    local dx = p1.x - p2.x
    local dy = p1.y - p2.y
    return math.sqrt(dx * dx + dy * dy)
end

local function SpanLength(span)
    return PointDist(span.StartPoint2D, span.EndPoint2D)
end

function FormatDogboneReport(job)
    local r = NewReport()
    local mtl_block = MaterialBlock()
    local spike_max_length = ToJobUnits(SPIKE_MAX_LENGTH_IN, mtl_block)
    local spike_return_tolerance = ToJobUnits(SPIKE_RETURN_TOLERANCE_IN, mtl_block)

    r:Blank()
    r:Header("DOGBONE RELIEF CHECK (CutOut layer)")

    local layer = job.LayerManager:FindLayerWithName("CutOut")
    if not layer then
        r:Line("  No layer named 'CutOut' found - cannot check for dogbones", "error")
        return r
    end

    local total_spikes = 0
    local panels_checked = 0
    local panels_with_spikes = 0

    local pos = layer:GetHeadPosition()
    while pos ~= nil do
        local obj
        obj, pos = layer:GetNext(pos)
        local ok, contour = pcall(function() return obj:GetContour() end)
        if ok and contour then
            panels_checked = panels_checked + 1
            local panel_spikes = 0

            -- Collect spans into a flat array first (need to look at
            -- pairs, and GetNext() only walks forward one at a time)
            local spans = {}
            local span_pos = contour:GetHeadPosition()
            while span_pos ~= nil do
                local span
                span, span_pos = contour:GetNext(span_pos)
                table.insert(spans, span)
            end

            local i = 1
            while i < #spans do
                local s1 = spans[i]
                local s2 = spans[i + 1]
                if s1.IsLineType and s2.IsLineType
                   and SpanLength(s1) < spike_max_length
                   and SpanLength(s2) < spike_max_length
                   and PointDist(s2.EndPoint2D, s1.StartPoint2D) < spike_return_tolerance then
                    panel_spikes = panel_spikes + 1
                    i = i + 2  -- consume both spans, don't re-check s2 as a new s1
                else
                    i = i + 1
                end
            end

            total_spikes = total_spikes + panel_spikes
            if panel_spikes > 0 then
                panels_with_spikes = panels_with_spikes + 1
            end
        end
    end

    r:Line(string.format(
        "  Panels checked: %d   Panels with dogbone spikes: %d   Total spikes: %d",
        panels_checked, panels_with_spikes, total_spikes
    ))

    if total_spikes == 0 then
        r:Line("  NO DOGBONE RELIEF CUTS DETECTED - inside corners may not fit", "error")
    elseif panels_with_spikes < panels_checked then
        r:Line(string.format(
            "  %d of %d panels have NO dogbone spikes - check these individually",
            panels_checked - panels_with_spikes, panels_checked
        ), "error")
    end

    return r
end

-- Offset radius / dogbone sizing check, added 2026-08. Derived directly
-- from Box_Creator.lua's own source (main() / CreateDogboneProfile /
-- GetEndPointArcBisector), not guessed:
--
--   offset_radius = 0.5*tool_diameter - allowance
--
-- This is the amount the "Box" (design) layer is offset OUTWARD to
-- produce the "CutOut" (actual cut) layer - it shows up directly as the
-- radius of the ARC spans rounding each convex corner on CutOut, so we
-- can read it straight off the geometry rather than diffing bounding
-- boxes. Each dogbone spike leg length should equal:
--
--   offset_radius * (1/sin(pi/4) - 1) = offset_radius * (sqrt(2) - 1)
--
-- (exact for 90-degree corners, which is every corner on a box panel).
--
-- STATUS: formulas come directly from source, hand-checked against real
-- pasted CutOut geometry (radius=0.0525, spike leg ~0.0218;
-- 0.0525*(sqrt(2)-1) = 0.02175 - matches within the precision of that
-- hand-eyeballed data), and confirmed again in the 2026-08-13 live
-- test run.
--
-- We can't read the "Allowance" value directly (not exposed anywhere
-- found in the SDK - see KNOWN GAPS in header), so the tool-radius check
-- only flags if the measured offset radius is LARGER than the tool
-- radius (impossible under normal use - offset_radius can only be
-- smaller than or equal to tool_radius) or MUCH smaller (a plausibility
-- check, since allowance is normally a small clearance, not a large
-- fraction of the tool radius).
CORNER_ARC_MAX_RADIUS_IN = 0.2  -- inches - upper bound for "this is a corner-rounding arc", not some other feature
OFFSET_VS_TOOL_TOLERANCE_IN = 0.005  -- inches
OFFSET_PLAUSIBLE_MIN_FRACTION = 0.5  -- flag if measured offset < 50% of tool radius (unitless ratio, no conversion needed)
SPIKE_LENGTH_FACTOR = math.sqrt(2) - 1  -- ~0.41421, exact for 90-degree corners (unitless ratio)
SPIKE_LENGTH_TOLERANCE_IN = 0.005  -- inches

function FormatOffsetRadiusReport(job)
    local r = NewReport()
    local mtl_block = MaterialBlock()
    local units = mtl_block.InMM and "mm" or "inches"
    local corner_arc_max_radius = ToJobUnits(CORNER_ARC_MAX_RADIUS_IN, mtl_block)
    local offset_vs_tool_tolerance = ToJobUnits(OFFSET_VS_TOOL_TOLERANCE_IN, mtl_block)
    local spike_length_tolerance = ToJobUnits(SPIKE_LENGTH_TOLERANCE_IN, mtl_block)
    local spike_max_length = ToJobUnits(SPIKE_MAX_LENGTH_IN, mtl_block)
    local spike_return_tolerance = ToJobUnits(SPIKE_RETURN_TOLERANCE_IN, mtl_block)
    local allowance_target = ToJobUnits(ALLOWANCE_TARGET_IN, mtl_block)
    local allowance_tolerance = ToJobUnits(ALLOWANCE_TOLERANCE_IN, mtl_block)

    r:Blank()
    r:Header("OFFSET RADIUS / DOGBONE SIZING CHECK")

    local layer = job.LayerManager:FindLayerWithName("CutOut")
    if not layer then
        r:Line("  No layer named 'CutOut' found - cannot check offset/dogbone sizing", "error")
        return r
    end

    -- Pass 1: measure the corner-rounding arc radius and dogbone spike
    -- leg lengths directly from the geometry
    local arc_radii = {}
    local spike_lengths = {}

    local pos = layer:GetHeadPosition()
    while pos ~= nil do
        local obj
        obj, pos = layer:GetNext(pos)
        local ok, contour = pcall(function() return obj:GetContour() end)
        if ok and contour then
            local spans = {}
            local span_pos = contour:GetHeadPosition()
            while span_pos ~= nil do
                local span
                span, span_pos = contour:GetNext(span_pos)
                table.insert(spans, span)
            end

            local i = 1
            while i <= #spans do
                local s1 = spans[i]
                if s1.IsArcType then
                    local ok2, radius = pcall(function()
                        local centre = Point3D()
                        local arc_span = CastSpanToArcSpan(s1)
                        return arc_span:RadiusAndCentre(centre)
                    end)
                    if ok2 and radius < corner_arc_max_radius then
                        table.insert(arc_radii, radius)
                    end
                    i = i + 1
                elseif i < #spans and s1.IsLineType and spans[i + 1].IsLineType
                       and SpanLength(s1) < spike_max_length
                       and SpanLength(spans[i + 1]) < spike_max_length
                       and PointDist(spans[i + 1].EndPoint2D, s1.StartPoint2D) < spike_return_tolerance then
                    table.insert(spike_lengths, SpanLength(s1))
                    i = i + 2
                else
                    i = i + 1
                end
            end
        end
    end

    if #arc_radii == 0 then
        r:Line("  No corner-rounding arcs found - cannot measure offset radius", "error")
        return r
    end

    local radius_min, radius_max, radius_sum = arc_radii[1], arc_radii[1], 0
    for _, rad in ipairs(arc_radii) do
        radius_min = math.min(radius_min, rad)
        radius_max = math.max(radius_max, rad)
        radius_sum = radius_sum + rad
    end
    local measured_offset = radius_sum / #arc_radii

    r:Line(string.format(
        "  Measured offset radius: %.4f %s (from %d corner arcs, range %.4f-%.4f)",
        measured_offset, units, #arc_radii, radius_min, radius_max
    ))
    if (radius_max - radius_min) > offset_vs_tool_tolerance then
        r:Line("  Corner arc radii are NOT consistent across the job - check for mixed tools or hand-edited geometry", "error")
    end

    -- Compare to the tool actually assigned to the cutout toolpath
    local cutout_tool, fallback_note = FindToolByToolpathName("Box_Cut_Out")
    if fallback_note then
        r:Line("  Note: " .. fallback_note)
    end
    local tool_radius = nil

    if cutout_tool then
        -- ConvertUnitsFrom in Box_Creator.lua's own source converts the
        -- tool's diameter into the job's units before using it, since a
        -- tool can be defined in different units than the job - do the
        -- same here rather than assume cutout_tool.ToolDia is already in
        -- job units.
        local tool_dia = cutout_tool.ToolDia
        if cutout_tool.InMM ~= mtl_block.InMM then
            if cutout_tool.InMM then
                tool_dia = tool_dia / INCHES_TO_MM
            else
                tool_dia = tool_dia * INCHES_TO_MM
            end
        end
        tool_radius = 0.5 * tool_dia
        r:Line(string.format(
            "  Tool radius: %.4f %s (dia %.4f %s)", tool_radius, units, tool_dia, units
        ))
        if measured_offset > tool_radius + offset_vs_tool_tolerance then
            r:Line("  Measured offset EXCEEDS tool radius - toolpath may not match the assigned tool", "error")
        elseif measured_offset < OFFSET_PLAUSIBLE_MIN_FRACTION * tool_radius then
            r:Line("  Measured offset is much smaller than tool radius - check tool assignment", "error")
        end
    else
        r:Line("  No toolpath/tool found - cannot compare offset to tool radius", "error")
    end

    -- Allowance (clearance) check, added 2026-08. Box Creator's own
    -- formula (see main() in Box_Creator.lua) is:
    --     offset_radius = 0.5*tool_diameter - allowance
    -- We've already measured offset_radius directly off the geometry and
    -- tool_radius from the assigned tool, so Allowance falls right out:
    --     allowance = tool_radius - offset_radius
    -- This closes the KNOWN GAPS item about Allowance not being directly
    -- exposed by the SDK - we don't need direct access, we derive it.
    if tool_radius then
        local derived_allowance = tool_radius - measured_offset
        r:Line(string.format(
            "  Derived Allowance: %.4f %s (target %.4f %s)",
            derived_allowance, units, allowance_target, units
        ))
        if math.abs(derived_allowance - allowance_target) > allowance_tolerance then
            r:Line(string.format(
                "  ALLOWANCE IS %.4f %s, expected %.4f %s",
                derived_allowance, units, allowance_target, units
            ), "error")
        end
    end

    -- Dogbone spike sizing, using the offset_radius we just measured
    if #spike_lengths == 0 then
        r:Line("  (no dogbone spikes found here - see separate dogbone presence check)")
    else
        local expected_spike = measured_offset * SPIKE_LENGTH_FACTOR
        local bad_spikes = 0
        for _, len in ipairs(spike_lengths) do
            if math.abs(len - expected_spike) > spike_length_tolerance then
                bad_spikes = bad_spikes + 1
            end
        end
        r:Line(string.format(
            "  Dogbone spike length: expected %.4f %s, checked %d spikes",
            expected_spike, units, #spike_lengths
        ))
        if bad_spikes > 0 then
            r:Line(string.format(
                "  %d of %d dogbone spikes are the WRONG LENGTH for the measured offset radius",
                bad_spikes, #spike_lengths
            ), "error")
        end
    end

    return r
end

